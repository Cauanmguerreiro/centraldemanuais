const PAGINAS = {
  campanhas: "campanhas.html",
  produtos: "produtos.html",
  lojas: "lojas.html"
};

function irPara(guia, passo) {
  const atual = document.body.dataset.page;
  if (guia && guia !== atual) {
    window.location.href = PAGINAS[guia] + (passo ? "#" + passo : "");
    return;
  }
  const alvo = passo && document.getElementById(passo);
  if (!alvo) return;
  alvo.scrollIntoView({ block: "start", behavior: "smooth" });
  alvo.classList.remove("destaque");
  void alvo.offsetWidth;
  alvo.classList.add("destaque");
}

document.querySelectorAll(".midia").forEach(box => {
  const item = MIDIA[box.dataset.chave];

  if (!item || !item.src) {
    box.innerHTML = '<div class="pendente"><span class="tag">EM PRODUÇÃO</span><p>A mídia deste passo ainda não foi adicionada. As instruções acima já valem para a versão atual do painel.</p></div>';
    return;
  }

  const rotulo = item.tipo === "imagem" ? "Tela do sistema" : "Vídeo do passo";
  const conteudo = item.tipo === "imagem"
    ? `<img src="${item.src}" alt="${item.cap || "Tela do sistema"}" loading="lazy">`
    : `<video src="${item.inicio ? item.src + "#t=" + item.inicio : item.src}"${item.poster ? ' poster="' + item.poster + '"' : ""} controls preload="metadata" playsinline title="${item.cap || "Vídeo do passo"}"></video>`;
  const legenda = item.cobre
    ? `${item.cap} · <b>o mesmo vídeo cobre os ${item.cobre}</b>`
    : (item.cap || "");

  box.innerHTML = `<p class="rotulo">${rotulo}</p><div class="quadro">${conteudo}</div>${legenda ? '<p class="legenda">' + legenda + "</p>" : ""}`;
});

document.addEventListener("click", event => {
  const destino = event.target.closest("[data-ir]");
  if (!destino) return;
  irPara(destino.dataset.ir, destino.dataset.passo);
});

(() => {
  const caixas = [...document.querySelectorAll("[data-check]")];
  if (!caixas.length) return;

  const contador = document.getElementById("check-contador");
  const limpar = document.getElementById("check-limpar");
  const chave = "agaclube-check";

  const ler = () => {
    try { return JSON.parse(localStorage.getItem(chave) || "{}"); }
    catch { return {}; }
  };
  const gravar = estado => {
    try { localStorage.setItem(chave, JSON.stringify(estado)); }
    catch {}
  };
  const contar = () => {
    if (contador) contador.textContent = `${caixas.filter(caixa => caixa.checked).length} de ${caixas.length}`;
  };

  const salvo = ler();
  caixas.forEach(caixa => {
    caixa.checked = Boolean(salvo[caixa.dataset.check]);
    caixa.addEventListener("change", () => {
      const estado = ler();
      estado[caixa.dataset.check] = caixa.checked;
      gravar(estado);
      contar();
    });
  });

  limpar?.addEventListener("click", () => {
    caixas.forEach(caixa => { caixa.checked = false; });
    gravar({});
    contar();
  });

  contar();
})();

if (window.matchMedia("(max-width:1000px)").matches) {
  document.querySelectorAll("nav.lado").forEach(nav => {
    const detalhes = document.createElement("details");
    detalhes.className = "indice";
    detalhes.innerHTML = '<summary>Índice do guia</summary><div class="conteudo"></div>';
    detalhes.querySelector(".conteudo").append(...nav.childNodes);
    nav.append(detalhes);
    nav.addEventListener("click", event => {
      if (event.target.closest("a")) detalhes.open = false;
    });
  });
}

const passos = [...document.querySelectorAll(".passo, .check")];
const links = new Map([...document.querySelectorAll('nav.lado a[href^="#"]')]
  .map(link => [link.getAttribute("href").slice(1), link]));

function marcarPassoAtual() {
  if (!passos.length) return;
  let atual = passos[0];
  passos.forEach(passo => {
    if (passo.getBoundingClientRect().top <= 130) atual = passo;
  });
  links.forEach(link => link.classList.remove("ativo"));
  links.get(atual.id)?.classList.add("ativo");
}

window.addEventListener("scroll", marcarPassoAtual, { passive: true });
window.addEventListener("load", () => {
  if (window.location.hash) {
    const alvo = document.querySelector(window.location.hash);
    if (alvo) setTimeout(() => irPara(document.body.dataset.page, alvo.id), 0);
  }
  marcarPassoAtual();
});
